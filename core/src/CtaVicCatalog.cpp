std::optional<CtaVicInfo> CtaVicCatalog::lookup(std::uint8_t video_identification_code)
{
	const auto found = std::lower_bound(
		known_vics.begin(), known_vics.end(), video_identification_code,
		[](const CtaVicInfo &info, std::uint8_t code) {
			return info.video_identification_code < code;
		});

	if (found == known_vics.end() || found->video_identification_code != video_identification_code)
		return std::nullopt;

	return *found;
}

